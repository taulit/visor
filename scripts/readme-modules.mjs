#!/usr/bin/env node
// Writes the table of built-in modules into README.md between two marker
// comments, or with --check only compares it. The id, slot and name of each
// module come from src/prefs/builtin-modules.ts (tests/prefs-table.test.ts keeps
// that table in step with src/modules/). The sentence about what a module shows
// is kept here; a module without one, or one for a module that is gone, fails.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
const readme = new URL('README.md', root);
const START = '<!-- modules:start (generated by scripts/readme-modules.mjs; do not edit) -->';
const END = '<!-- modules:end -->';

const SHOWS = {
  media:
    'Players that report through MPRIS: cover, title, artist, the controls and a progress line.',
  timers:
    'Timers, alarms and stopwatches started from the search, with a notification when one ends.',
  downloads:
    'Running downloads, found through the partial files browsers write, then Open and Show in folder.',
  t3: 'Agent sessions of the T3 Code server, with approvals you can answer in the row.',
  upcoming:
    'The next events of the calendars GNOME knows, with a Join button for video calls shortly before the start.',
  notifications: 'The notifications of the shell, newest first, with Do Not Disturb and Clear all.',
};

const { BUILTIN_MODULES, SLOTS } = await import(
  pathToFileURL(new URL('src/prefs/builtin-modules.ts', root).pathname).href
);

const problems = [];
for (const { id } of BUILTIN_MODULES) if (!(id in SHOWS)) problems.push(`no sentence for ${id}`);
for (const id of Object.keys(SHOWS))
  if (!BUILTIN_MODULES.some(module => module.id === id))
    problems.push(`sentence for ${id}, which is not a built-in module`);
if (problems.length > 0) {
  console.error(`readme-modules: ${problems.join('; ')}`);
  process.exit(1);
}

const slotTitle = slot => SLOTS.find(entry => entry.slot === slot)?.title ?? slot;

/** The table, padded the way Prettier pads Markdown tables. */
function table() {
  const head = ['Module', 'Slot', 'What it shows'];
  const rows = BUILTIN_MODULES.map(module => [
    module.name,
    slotTitle(module.slot),
    SHOWS[module.id],
  ]);
  const widths = head.map((cell, column) =>
    Math.max(cell.length, ...rows.map(row => row[column].length)),
  );
  const line = cells => `| ${cells.map((cell, i) => cell.padEnd(widths[i])).join(' | ')} |`;
  return [
    line(head),
    `| ${widths.map(width => '-'.repeat(width)).join(' | ')} |`,
    ...rows.map(line),
  ].join('\n');
}

const text = readFileSync(readme, 'utf8');
const from = text.indexOf(START);
const to = text.indexOf(END);
if (from < 0 || to < from) {
  console.error(`readme-modules: README.md needs the lines\n${START}\n${END}`);
  process.exit(1);
}

const next = `${text.slice(0, from + START.length)}\n\n${table()}\n\n${text.slice(to)}`;
if (process.argv.includes('--check')) {
  if (next !== text) {
    console.error('readme-modules: the module table in README.md is stale; run `pnpm run readme`.');
    process.exit(1);
  }
  console.log('readme-modules: ok');
} else if (next !== text) {
  writeFileSync(readme, next);
  console.log('readme-modules: README.md updated');
} else {
  console.log('readme-modules: nothing to change');
}
